<#
.SYNOPSIS
    Generates Payload.wxs: one MSI component per file in the packaged folder.

.DESCRIPTION
    Hand-maintaining a component list for a WinUI payload is pointless: the file
    set changes with every Windows App SDK update. This walks the folder, nests
    <Directory> elements to mirror it, and emits one <Component> with one <File>
    per file, followed by a ComponentGroup that Product.wxs consumes.

    Ids are derived from the relative path, so a rebuild that keeps the same files
    produces the same ids. Component Guid="*" lets WiX generate stable component
    GUIDs from the same paths.

.PARAMETER AppDir
    Folder to package, typically dist\TaskManagerPlusPlus-<version>-win-x64.

.PARAMETER Output
    Path of the .wxs file to write.

.EXAMPLE
    tools\msi\harvest.ps1 -AppDir dist\TaskManagerPlusPlus-26111901-win-x64 -Output build\msi\Payload.wxs
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$AppDir,
    [Parameter(Mandatory = $true)][string]$Output
)

$ErrorActionPreference = 'Stop'

$app = (Resolve-Path -LiteralPath $AppDir).Path.TrimEnd('\')
$files = @(Get-ChildItem -LiteralPath $app -Recurse -File)
if ($files.Count -eq 0) { throw "no files under $app" }

function Get-StableId([string]$Prefix, [string]$Value) {
    $sha = [System.Security.Cryptography.SHA1]::Create()
    try {
        $hash = $sha.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Value.ToLowerInvariant()))
    }
    finally {
        $sha.Dispose()
    }
    $hex = -join ($hash | ForEach-Object { $_.ToString('x2') })
    return ('{0}{1}' -f $Prefix, $hex.Substring(0, 16))
}

function Escape-Xml([string]$Value) {
    return [System.Security.SecurityElement]::Escape($Value)
}

$entries = foreach ($file in $files) {
    $relative = $file.FullName.Substring($app.Length).TrimStart('\')
    $directory = Split-Path -Parent $relative
    if (-not $directory) { $directory = '' }

    [pscustomobject]@{
        Name      = $file.Name
        Full      = $file.FullName
        Relative  = $relative
        Directory = $directory
    }
}

# Every directory that holds a file, plus the ancestors between them.
$directories = @{ '' = $true }
foreach ($entry in $entries) {
    if (-not $entry.Directory) { continue }
    $current = ''
    foreach ($part in ($entry.Directory -split '\\')) {
        if (-not $part) { continue }
        $current = if ($current) { "$current\$part" } else { $part }
        $directories[$current] = $true
    }
}

$directoryIds = @{}
foreach ($key in $directories.Keys) {
    if ($key) { $directoryIds[$key] = Get-StableId 'dir_' $key }
}

$componentIds = New-Object System.Collections.ArrayList
$builder = New-Object System.Text.StringBuilder

function Get-DirectChildren([string]$Parent) {
    $prefix = if ($Parent) { "$Parent\" } else { '' }
    return @($directories.Keys | Where-Object {
        $_ -ne $Parent -and
        $_.StartsWith($prefix, [System.StringComparison]::OrdinalIgnoreCase) -and
        (($_.Substring($prefix.Length)) -notmatch '\\')
    } | Sort-Object)
}

function Write-Directory([string]$Relative, [int]$Depth) {
    $indent = ' ' * ($Depth * 2)

    if ($Relative) {
        [void]$builder.AppendLine(('{0}<Directory Id="{1}" Name="{2}">' -f $indent, $directoryIds[$Relative], (Escape-Xml (Split-Path -Leaf $Relative))))
    }

    $childIndent = if ($Relative) { ' ' * (($Depth + 1) * 2) } else { $indent }

    foreach ($entry in ($entries | Where-Object { $_.Directory -eq $Relative } | Sort-Object Name)) {
        $componentId = Get-StableId 'cmp_' $entry.Relative
        $fileId = Get-StableId 'fil_' $entry.Relative
        [void]$componentIds.Add($componentId)

        [void]$builder.AppendLine(('{0}<Component Id="{1}" Guid="*">' -f $childIndent, $componentId))
        [void]$builder.AppendLine(('{0}  <File Id="{1}" Name="{2}" Source="{3}" KeyPath="yes" />' -f $childIndent, $fileId, (Escape-Xml $entry.Name), (Escape-Xml $entry.Full)))
        [void]$builder.AppendLine(('{0}</Component>' -f $childIndent))
    }

    foreach ($child in (Get-DirectChildren $Relative)) {
        Write-Directory $child ($Depth + 1)
    }

    if ($Relative) {
        [void]$builder.AppendLine(('{0}</Directory>' -f $indent))
    }
}

[void]$builder.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$builder.AppendLine('<!-- Generated by tools/msi/harvest.ps1 from the packaged folder. Do not edit. -->')
[void]$builder.AppendLine('<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">')
[void]$builder.AppendLine('  <Fragment>')
[void]$builder.AppendLine('    <DirectoryRef Id="INSTALLFOLDER">')
Write-Directory '' 3
[void]$builder.AppendLine('    </DirectoryRef>')
[void]$builder.AppendLine('  </Fragment>')
[void]$builder.AppendLine('  <Fragment>')
[void]$builder.AppendLine('    <ComponentGroup Id="PayloadComponents">')
foreach ($id in $componentIds) {
    [void]$builder.AppendLine(('      <ComponentRef Id="{0}" />' -f $id))
}
[void]$builder.AppendLine('    </ComponentGroup>')
[void]$builder.AppendLine('  </Fragment>')
[void]$builder.AppendLine('</Wix>')

$parent = Split-Path -Parent $Output
if ($parent -and -not (Test-Path -LiteralPath $parent)) {
    New-Item -ItemType Directory -Path $parent -Force | Out-Null
}

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($Output, $builder.ToString(), $utf8)

Write-Host ("harvest: {0} file(s), {1} component(s) -> {2}" -f $entries.Count, $componentIds.Count, $Output)
